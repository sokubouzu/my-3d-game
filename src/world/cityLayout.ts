import { CITY_METRICS } from './collisionWorld';

export type AssetCategory = 'buildings' | 'vehicles' | 'props';
export type ScaleFitMode = 'height' | 'length';

export interface CityAssetPlacement {
  /** 配置インスタンス固有 ID */
  instanceId: string;
  /** docs/ASSET_MANIFEST.json の id */
  assetId: string;
  /** カテゴリ */
  category: AssetCategory;
  /** public/ からの相対 URL (./assets/...) */
  url: string;
  /** 配置 X 座標 (m) */
  x: number;
  /** 配置 Z 座標 (m) */
  z: number;
  /** 地面からの追加 Y オフセット (m)。通常 0 (自動接地) */
  yOffset?: number;
  /** Y 軸回転 (rad) */
  rotationY: number;
  /** スケール基準: 建物・小物は height、車両・線路は length */
  fitMode: ScaleFitMode;
  /** 基準軸の目標寸法 (m) */
  targetSize: number;
  /** 水平フットプリント（幅・奥行の最大辺）上限 (m) */
  maxFootprint: number;
  /** コリジョンを有効にするか */
  hasCollision: boolean;
  /** コリジョンボックスの縮小率 (0.85〜0.98 程度、軒先・ミラーの引っかかり緩和) */
  colliderShrink?: number;
  /** ロード完了前の暫定コリジョン幅・奥行 (m) */
  placeholderFootprint?: { width: number; depth: number; height: number };
  /** リアルタイムシャドウを落とすか (M1 iPad Air 最適化のため高ポリゴンは false) */
  castShadow: boolean;
  /** ロード優先度 (小さいほど先にロード: 1=交差点周辺, 2=車両・小物, 3=中距離建物, 4=大型ジオラマ) */
  priority: number;
}

